function classwiz(
  id: string,
  model: string,
  solar: boolean,
  bodyTop: string,
  bodyBottom: string,
): CalculatorSpec {
  return {
    id,
    brand: 'Casio',
    model,
    label: `ClassWiz ${model}`,
    family: 'classwiz',
    exam: { gcse: true, alevel: false },
    features: ['fraction', 'surd', 'trig', 'angle-units', 'scientific-notation'],
    shell: {
      bodyTop,
      bodyBottom,
      accent: '#2f6fbe',
      solar,
      label: 'CLASSWIZ',
      edition: '2nd edition',
    },
    display: { width: 192, height: 63, greyLevels: 4 },
    keys,
  };
}

